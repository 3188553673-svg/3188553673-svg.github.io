const context = new Proxy({}, { get: (o, k) => o[k] ?? (() => {}), set: (o, k, v) => (o[k] = v, true) });
globalThis.document = { createElement: () => ({ width: 256, height: 256, getContext: () => context }) };
function cpuScene(Prototype = ArenaScene.prototype) {
  return Object.assign(Object.create(Prototype), {
    available: true, disposed: false, selfId: 'self', selfTeam: 0, state: null, entities: new Map(), pickTargets: [], materials: new Map(), geometries: new Map(), textures: new Set(), actorBatchGeometries: new Map(), assetStatus: {},
    actors: new THREE.Group(), preview: new THREE.Group(), fxLayer: new THREE.Group(), projectiles: new Map(), effects: new Map(), localEffects: [], floaters: [], seenEvents: new Set(),
    motionPlayback: new SnapshotPlayback(), focus: new THREE.Vector3(), focusTarget: new THREE.Vector3(), predictor: new MovementPredictor(), raycaster: new THREE.Raycaster(),
  });
}
const unit = x => ({ id: 'remote', kind: 'hero', team: 1, champion: 'garen', name: 'remote', x, z: 0, hp: 500, maxHp: 500, mana: 0, maxMana: 0, level: 1, dead: false });
const state = (time, x) => ({ phase: 'playing', time, tick: Math.round(time * 20), players: [], heroes: [unit(x)], minions: [], structures: [], projectiles: [], effects: [], events: [] });

test('same-tick acknowledgement preserves remote velocity and extrapolation epoch; same-tick teleport snaps', () => {
  const scene = cpuScene();
  scene.setState(state(.1, 0), 'self'); scene.setState(state(.2, .66), 'self');
  const entry = scene.entities.get('remote'), sampledAt = scene.motionPlayback.arrivedAt;
  assert.ok(Math.abs(entry.vx - 6.6) < .000001);
  scene.setState(state(.2, .66), 'self');
  assert.ok(Math.abs(entry.vx - 6.6) < .000001, 'an acknowledgement must not zero walking velocity');
  assert.equal(scene.motionPlayback.arrivedAt, sampledAt, 'an acknowledgement must not rewind playback time');
  scene.setState(state(.2, 6), 'self');
  assert.equal(entry.vx, 0); assert.equal(entry.group.position.x, 6);
});

test('remote flash is snapped rather than extrapolated and a finished match cannot keep walking', () => {
  const scene = cpuScene();
  scene.setState(state(.1, 0), 'self'); scene.setState(state(.15, .33), 'self');
  scene.setState(state(.2, 6.33), 'self');
  const entry = scene.entities.get('remote');
  assert.equal(entry.vx, 0); assert.equal(entry.group.position.x, 6.33);
  scene.setState(state(.25, 6.66), 'self'); assert.ok(entry.vx > 0);
  scene.setState({ ...state(.25, 6.66), phase: 'finished' }, 'self');
  assert.equal(entry.vx, 0); assert.equal(entry.vz, 0); assert.equal(entry.group.position.x, 6.66);
  assert.equal(scene.predictor.step(.016), null);
});

test('pick volumes remain raycastable while excluded from the camera render layer', () => {
  const scene = cpuScene(), entry = scene.createEntity(unit(0));
  assert.equal(entry.pick.layers.test(new THREE.Camera().layers), false);
  scene.actors.updateMatrixWorld(true); scene.raycaster.layers.set(1); scene.raycaster.ray.set(new THREE.Vector3(0, 2, 5), new THREE.Vector3(0, 0, -1));
  assert.ok(scene.raycaster.intersectObjects(scene.pickTargets, false).length > 0);
});

function modelMetrics(root) {
  let meshes = 0, triangles = 0; const colorSum = [0, 0, 0];
  root.updateMatrixWorld(true);
  root.traverse(o => {
    if (!o.isMesh) return; meshes++;
    const index = o.geometry.index, positions = o.geometry.attributes.position, colors = o.geometry.attributes.color, count = index?.count ?? positions.count;
    triangles += count / 3;
    for (let i = 0; i < count; i++) { const j = index ? index.getX(i) : i; colorSum[0] += o.material.color.r * (colors ? colors.getX(j) : 1); colorSum[1] += o.material.color.g * (colors ? colors.getY(j) : 1); colorSum[2] += o.material.color.b * (colors ? colors.getZ(j) : 1); }
  });
  return { meshes, triangles, colorSum, bounds: new THREE.Box3().setFromObject(root) };
}
test('minion batching retains triangles, shape and per-vertex colors while reducing object submissions', async () => {
  // Frozen geometry/color metrics captured before the optimization, not generated by it.
  const baseline = JSON.parse(await fs.readFile(new URL('./fixtures/minion-baseline.json', import.meta.url), 'utf8'));
  for (const team of [0, 1]) for (const method of ['meleeMinion', 'casterMinion']) {
    const before = baseline[`${method}:${team}`], after = modelMetrics(cpuScene()[method](team));
    assert.ok(after.meshes < before.meshes, method); assert.equal(after.triangles, before.triangles);
    assert.ok(after.bounds.min.distanceTo(new THREE.Vector3(...before.bounds.min)) < .00001); assert.ok(after.bounds.max.distanceTo(new THREE.Vector3(...before.bounds.max)) < .00001);
    for (let c = 0; c < 3; c++) assert.ok(Math.abs(after.colorSum[c] - before.colorSum[c]) < .001);
  }
});

test('automatic resolution needs sustained slow foreground frames, high quality remains fixed', () => {
  const budget = new FrameBudget(2), info = { calls: 100, triangles: 10000 };
  let now = 0;
  for (let i = 0; i < 95; i++) { now += 33.33; budget.sample(now, 8, info); }
  assert.ok(budget.ratio < 1.7 && budget.ratio >= 1);
  assert.ok(budget.metrics.frameP95Ms > 33); assert.equal(budget.metrics.calls, 100);
  budget.setQuality('high');
  for (let i = 0; i < 160; i++) { now += 40; budget.sample(now, 8, info); }
  assert.equal(budget.ratio, 2);
  budget.sample(now + 5000, 8, info, false); budget.sample(now + 10000, 8, info, true);
  assert.equal(budget.frames.length, 0, 'background pause must not become a foreground frame sample');
});
